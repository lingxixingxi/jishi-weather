/// 找距离 ([lat], [lon]) 最近的雷达站
///
/// 单站雷达覆盖半径 256 km，最近站点通常就在覆盖内；
/// 若最近站点距离超过覆盖半径，说明该位置本身没有单站雷达覆盖。
///
/// 这里只用「纬度差 + 经度差 × cos(纬度)」的平方距离近似 —— 
/// 目的是「选最近站点」，不追求大圆距离精度，
/// 也避免为几个三角函数让这个纯数据文件依赖 dart:math。
RadarStation nearestRadarStation(double lat, double lon) {
  final cosLat = _cosDeg(lat);
  var best = kRadarStations.first;
  var bestD = double.infinity;
  for (final s in kRadarStations) {
    final dLat = s.lat - lat;
    final dLon = (s.lon - lon) * cosLat;
    final d = dLat * dLat + dLon * dLon;
    if (d < bestD) {
      bestD = d;
      best = s;
    }
  }
  return best;
}

/// 纬度的余弦（度制）
///
/// 用查表 + 线性插值：站点表只在「选最近站点」时用一次，
/// 精度 0.001 足够，也免去为 cos 引入 dart:math。
double _cosDeg(double deg) {
  const table = <double>[
    1.0000, 0.9998, 0.9994, 0.9986, 0.9976, 0.9962, 0.9945, 0.9925,
    0.9903, 0.9877, 0.9848, 0.9816, 0.9781, 0.9744, 0.9703, 0.9659,
    0.9613, 0.9563, 0.9511, 0.9455, 0.9397, 0.9336, 0.9272, 0.9205,
    0.9135, 0.9063, 0.8988, 0.8910, 0.8829, 0.8746, 0.8660, 0.8572,
    0.8480, 0.8387, 0.8290, 0.8192, 0.8090, 0.7986, 0.7880, 0.7771,
    0.7660, 0.7547, 0.7431, 0.7314, 0.7193, 0.7071, 0.6947, 0.6820,
    0.6691, 0.6561, 0.6428, 0.6293, 0.6157, 0.6018, 0.5878, 0.5736,
    0.5592, 0.5446, 0.5299, 0.5150, 0.5000, 0.4848, 0.4695, 0.4540,
    0.4384, 0.4226, 0.4067, 0.3907, 0.3746, 0.3584, 0.3420, 0.3256,
    0.3090, 0.2924, 0.2756, 0.2588, 0.2419, 0.2250, 0.2079, 0.1908,
    0.1736, 0.1564, 0.1392, 0.1219, 0.1045, 0.0872, 0.0698, 0.0523,
    0.0349, 0.0175, 0.0000,
  ];
  final a = deg.abs();
  if (a >= 90) return 0.0;
  final pos = a / 90.0 * (table.length - 1);
  final i = pos.floor();
  final f = pos - i;
  if (i >= table.length - 1) return table.last;
  return table[i] + (table[i + 1] - table[i]) * f;
}
